"""Prohibited mutations of the payment-event ledger, run against its OFFLINE structural pins
(test/payment-event-ledger-structure.test.mjs). The database half has its own harness (test/payment_event_ledger_pg/run.sh runs
every mutation of the SQL against the real Postgres suite); this one answers a different question: does every PIN go red when the
thing it guards is broken?

    python3 test/payment_event_ledger_mutants.py                  # every mutation, then the coverage check
    python3 test/payment_event_ledger_mutants.py name [name ...]

For each mutation it edits files IN PLACE, runs the structural test, and ALWAYS restores the originals (even on error or ^C), then
re-runs the unmutated test and compares every touched file byte for byte. An anchor that does not match the stated number of times is
a harness failure, never a pass. Exit 0 only if (1) every mutation turned the test red, and (2) EVERY pin of the test was the pin
that went red for at least one mutation. A pin that no mutation has ever turned red is a pin nobody has shown can fail, and is
reported as UNCOVERED. (Manual, like follow_report_mutants.py: CI runs the test, not this loop.)

A mutation is a list of (file, old, new[, count]). `count` defaults to 1, and None means "every occurrence, at least one". `old` None
with a file that does not exist creates it (and removes it afterwards); with a file that does exist it replaces the whole file.
The SQL mutations named in test/payment_event_ledger_pg/mutate.py are reused as they are, by name.
"""
