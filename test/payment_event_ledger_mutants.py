PIN = re.compile(r'^(PASS|FAIL) — ([0-9]+[a-z]*(?:-control)?):')


def run_test():
    r = subprocess.run(['node', str(ROOT / TEST)], cwd=ROOT, capture_output=True, text=True)
    pins = {}
    for line in r.stdout.splitlines():
        m = PIN.match(line)
        if m:
            pins[m.group(2)] = m.group(1)
    return r.returncode, pins


def apply(mut, originals, created):
    """edit the tree; returns None on success or a message on a harness fault"""
    for item in mut:
        file, old, new = item[0], item[1], item[2]
        count = item[3] if len(item) > 3 else 1
        p = ROOT / file
        if old is None:
            if p.exists():
                originals.setdefault(file, p.read_text())
            else:
                d = p.parent
                missing = []
                while not d.exists():
                    missing.append(d)
                    d = d.parent
                p.parent.mkdir(parents=True, exist_ok=True)
                created.append((p, missing))
            p.write_text(new)
            continue
        originals.setdefault(file, p.read_text())
        text = p.read_text()
        found = text.count(old)
        if (count is None and found < 1) or (count is not None and found != count):
            return 'anchor matched %d time(s) in %s, expected %s' % (found, file, 'at least 1' if count is None else count)
        if old == new:
            return 'mutation changes nothing in %s' % file
        p.write_text(text.replace(old, new))
    return None


def restore(originals, created):
    for file, text in originals.items():
        (ROOT / file).write_text(text)
    for p, missing in created:
        if p.exists():
            p.unlink()
        for d in missing:
            if d.exists() and not any(d.iterdir()):
                d.rmdir()


def main():
    only = [a for a in sys.argv[1:] if not a.startswith('--')]
    unknown = [a for a in only if a not in M]
    if unknown:
        print('HARNESS — unknown mutation(s): ' + ', '.join(unknown))
        return 2
    rc, base = run_test()
    if rc != 0 or not base or any(v != 'PASS' for v in base.values()):
        print('HARNESS — the unmutated tree does not pass the structural test (%d pins read)' % len(base))
        return 2
    names = [k for k in M if not only or k in only]
    survived, harness, covered = [], [], set()
    for name in names:
        originals, created = {}, []
        try:
            fault = apply(M[name], originals, created)
            if fault:
                print('HARNESS  %-38s %s' % (name, fault))
                harness.append(name)
                continue
            rc, pins = run_test()
            red = sorted(k for k, v in pins.items() if v == 'FAIL')
            if rc != 0 and red:
                covered.update(red)
                print('killed   %-38s by %s' % (name, ', '.join(red[:8]) + (' …' if len(red) > 8 else '')))
            elif rc != 0:
                covered.add('(crash)')
                print('killed   %-38s by a crash before any pin printed' % name)
            else:
                print('SURVIVED %s' % name)
                survived.append(name)
        finally:
            restore(originals, created)
    rc, after = run_test()
    if rc != 0:
        print('HARNESS — the tree does not pass after restoring')
        return 2
    leftover = subprocess.run(['git', 'status', '--porcelain', '--', 'supabase/functions/lemonsqueezy-webhook'], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    if leftover or (ROOT / 'supabase/functions/lemonsqueezy-webhook').exists():
        print('HARNESS — a created file was not removed: ' + leftover)
        return 2
    uncovered = sorted(set(base) - covered, key=lambda s: (int(re.match(r'\d+', s).group()), s))
    ran = len(names) - len(harness)
    print('\n%d mutations run, %d killed, %d survived, %d harness faults; %d of %d pins were turned red by at least one mutation'
          % (ran, ran - len(survived), len(survived), len(harness), len(set(base) & covered), len(base)))
    if survived:
        print('SURVIVORS: ' + ', '.join(survived))
    if uncovered and not only:
        print('UNCOVERED PINS (no mutation has ever turned them red): ' + ', '.join(uncovered))
    return 1 if (survived or harness or (uncovered and not only)) else 0


if __name__ == '__main__':
    sys.exit(main())
