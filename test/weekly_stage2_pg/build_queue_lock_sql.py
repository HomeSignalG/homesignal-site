"""Generate docs/weekly-2a-publication-lock.sql from file 2. Never edit file 2a by hand.

File 2a is the publication lock for the QUEUE-ONLY release (files 1 and 2): a PUBLISHED edition (our video's address
recorded) refuses new assignments, research requests and disposition changes, exactly as a CLOSED one already does.
It replaces three functions of file 2, each the original body with ONE inserted line. The inserted line, its message and
its position are the ones file 9 (prepared separately, not part of this release) uses, so file 9 can later replace these
bodies without changing the lock. Nothing is retyped;
--check fails if the committed file differs from what this script makes.

    python3 test/weekly_stage2_pg/build_queue_lock_sql.py           # write
    python3 test/weekly_stage2_pg/build_queue_lock_sql.py --check   # compare
    python3 test/weekly_stage2_pg/build_queue_lock_sql.py --docs D  # regenerate inside a (mutated) copy of docs/
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DOCS = os.path.join(ROOT, "docs")
FUNC = re.compile(r"^create or replace function public\.(\w+)\(", re.M)
# THE LOCK LINE. File 9 (build_edition_topics_sql.py, not part of this release) inserts this same text at these same
# places; its tests compare the two once both exist on one branch.
PUBLISHED = "  if ed.video_url is not null then raise exception 'edition %% is published; %s', ed.edition_key using errcode = '55000'; end if;\n"
# Each lock line goes directly after that function's closed check, so a closed edition keeps its own message.
CLOSED = "  if ed.closed_at is not null then raise exception 'edition % is closed', ed.edition_key using errcode = '55000'; end if;\n"
CLOSED_DISP = "  if ed.closed_at is not null then raise exception 'edition % is closed; its decisions stand', ed.edition_key using errcode = '55000'; end if;\n"
F2 = "weekly-2-topic-queue.sql"
SUBS = {
    "_wk_lead_assign": [(CLOSED, CLOSED + PUBLISHED % "its topics are final")],
    "hs_weekly_lead_disposition": [(CLOSED_DISP, CLOSED_DISP + PUBLISHED % "its decisions stand")],
    "hs_weekly_lead_send_to_research": [(CLOSED, CLOSED + PUBLISHED % "its topics are final")],
}

HEAD = """-- Tab 20 · Weekly Report, 2a: THE PUBLICATION LOCK FOR THE QUEUE-ONLY RELEASE. DDL of record. PREPARED, NOT APPLIED TO PRODUCTION.
-- GENERATED by test/weekly_stage2_pg/build_queue_lock_sql.py from file 2. Do not edit by hand.
-- Needs: 1 and 2. Application order: 1 · 2 · 2a. One transaction; safe to apply twice. Creates no object.
--
-- A PUBLISHED edition (weekly_editions.video_url recorded) refuses new assignments, research requests and disposition
-- changes (include, defer, drop), with SQLSTATE 55000, exactly as a CLOSED edition already does. Before this file only
-- the page hid those actions. Open unpublished editions are unchanged, and a closed edition keeps its own messages
-- (its check still runs first).
-- It replaces three functions of file 2. Each body is file 2's with one inserted line; the line is the same text file 9
-- inserts at the same places, so applying file 9 later replaces these bodies with ones that lock the same way.
-- Owner, privileges, SECURITY DEFINER and search_path are unchanged; the grants below restate file 2's.
-- RE-APPLY HAZARD: re-applying file 2 after this file restores the unlocked bodies. Re-apply this file after it.
"""

GRANTS = """
do $$
declare f text;
begin
  foreach f in array array['_wk_lead_assign(uuid,uuid,text)', 'hs_weekly_lead_send_to_research(uuid,uuid,text)',
    'hs_weekly_lead_disposition(uuid,uuid,text,text)'] loop
    execute format('revoke all on function public.%s from public, anon, authenticated', f);
  end loop;
  foreach f in array array['hs_weekly_lead_send_to_research(uuid,uuid,text)', 'hs_weekly_lead_disposition(uuid,uuid,text,text)'] loop
    execute format('grant execute on function public.%s to authenticated', f);
  end loop;
end $$;
"""

OUT = os.path.join(DOCS, "weekly-2a-publication-lock.sql")


def function_text(fname, name):
    src = open(os.path.join(DOCS, fname), encoding="utf-8").read()
    starts = [m for m in FUNC.finditer(src) if m.group(1) == name]
    if len(starts) != 1:
        raise SystemExit("%s: %d definitions of %s" % (fname, len(starts), name))
    m = re.compile(r"^(end )?\$\$;\n", re.M).search(src, starts[0].start())
    if not m:
        raise SystemExit("%s: no end for %s" % (fname, name))
    return src[starts[0].start():m.end()]


def body(name, lenient):
    t = function_text(F2, name)
    for a, b in SUBS[name]:
        if lenient and t.count(a) == 0:
            continue   # a mutated copy rewrote the target line: keep the mutated body so the weakening is tested
        if t.count(a) != 1:
            raise SystemExit("%s: substitution matches %d times: %r" % (name, t.count(a), a[:80]))
        t = t.replace(a, b)
    return t


def build(lenient=False):
    parts = [HEAD, "\nbegin;\n"]
    for name in SUBS:
        parts.append("\n-- %s, from docs/%s with one inserted line (see the generator)\n" % (name, F2))
        parts.append(body(name, lenient))
    parts += [GRANTS, "\ncommit;\n"]
    return "".join(parts)


def main():
    global OUT, DOCS
    lenient = False
    if "--docs" in sys.argv:
        DOCS = sys.argv[sys.argv.index("--docs") + 1]
        OUT, lenient = os.path.join(DOCS, "weekly-2a-publication-lock.sql"), True
    text = build(lenient)
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == text
        print("weekly-2a matches its generator" if ok else "weekly-2a differs from its generator")
        return 0 if ok else 1
    open(OUT, "w", encoding="utf-8").write(text)
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
