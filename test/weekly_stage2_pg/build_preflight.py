#!/usr/bin/env python3
"""Build docs/weekly-preflight-queue-only.sql: the READ-ONLY production preflight for the queue-only release
(docs/weekly-1-base.sql + docs/weekly-2-topic-queue.sql).

The list of objects those two files create is NOT typed by hand: it is read from a disposable Postgres by comparing its
catalog before and after applying them. Run by run_queue_only.sh, which also runs the generated query twice:
  on a database WITHOUT the release  -> every prerequisite present, zero conflicts (verdict "go")
  on a database WITH the release     -> every created object reported as already existing (so the conflict check is
                                        known to see each one of them)

The query is one SELECT. It reads catalogs, the topic catalog's news rows (category names, not people) and COUNTS the
admin list. It selects no e-mail address, no secret and no subscriber data, because the workflow that runs it
(db-read.yml) prints its result to a public log.

  python3 build_preflight.py --snapshot before|after <file>   write this database's catalog snapshot
  python3 build_preflight.py --write <before> <after>         write the preflight file
  python3 build_preflight.py --check <before> <after>         fail if the committed file differs
"""
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, "docs", "weekly-preflight-queue-only.sql")
CATEGORIES = ["Air Quality", "Data Centers", "Water Quality"]   # the report categories the queue is known to need first

SNAPSHOT = """
select jsonb_build_object(
  'relations', (select coalesce(jsonb_agg(c.relname order by c.relname), '[]') from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public'),
  'functions', (select coalesce(jsonb_agg(distinct p.proname order by p.proname), '[]') from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public'),
  'types', (select coalesce(jsonb_agg(t.typname order by t.typname), '[]') from pg_type t join pg_namespace n on n.oid = t.typnamespace where n.nspname = 'public'),
  'constraints', (select coalesce(jsonb_agg(distinct c.conname order by c.conname), '[]') from pg_constraint c join pg_namespace n on n.oid = c.connamespace where n.nspname = 'public'),
  'triggers', (select coalesce(jsonb_agg(distinct t.tgname order by t.tgname), '[]') from pg_trigger t join pg_class c on c.oid = t.tgrelid
               join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and not t.tgisinternal))::text
"""


def snapshot():
    return json.loads(subprocess.run(["psql", "-X", "-q", "-tA", "-c", SNAPSHOT], capture_output=True, text=True, check=True).stdout)


def arr(names):
    return "array[" + ", ".join("'%s'" % n.replace("'", "''") for n in names) + "]::text[]"


def build(before, after):
    new = {k: sorted(set(after[k]) - set(before[k])) for k in after}
    assert new["relations"] and new["functions"], "the release created nothing?"
    return """-- Tab 20 · Weekly Report: READ-ONLY PRODUCTION PREFLIGHT for the queue-only release
-- (docs/weekly-1-base.sql + docs/weekly-2-topic-queue.sql). GENERATED by test/weekly_stage2_pg/build_preflight.py from
-- the objects those two files create on a disposable database. Do not edit by hand.
--
-- One SELECT. It changes nothing. It prints catalog names, the 'news' category names and COUNTS; no e-mail address, no
-- secret, no subscriber data. NOT YET RUN AGAINST PRODUCTION.
--
-- Read "verdict": 'go' means every prerequisite is present and nothing the release creates already exists.
-- Anything else lists what is missing or what already exists. A conflict matters because the files use
-- "create table if not exists" and "create or replace function": an object already there would be silently kept
-- (a table) or silently replaced (a function).
with want as (
  select %(relations)s as relations,
         %(functions)s as functions,
         %(types)s as types,
         %(constraints)s as constraints,
         %(triggers)s as triggers,
         %(categories)s as categories
), found as (
  select
    (select coalesce(jsonb_agg(c.relname order by c.relname), '[]'::jsonb) from pg_class c join pg_namespace n on n.oid = c.relnamespace
      where n.nspname = 'public' and c.relname = any (w.relations)) as relations,
    (select coalesce(jsonb_agg(distinct p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')'), '[]'::jsonb)
      from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public' and p.proname = any (w.functions)) as functions,
    (select coalesce(jsonb_agg(t.typname order by t.typname), '[]'::jsonb) from pg_type t join pg_namespace n on n.oid = t.typnamespace
      where n.nspname = 'public' and t.typname = any (w.types)) as types,
    (select coalesce(jsonb_agg(distinct c.conname), '[]'::jsonb) from pg_constraint c join pg_namespace n on n.oid = c.connamespace
      where n.nspname = 'public' and c.conname = any (w.constraints)) as constraints,
    (select coalesce(jsonb_agg(distinct t.tgname), '[]'::jsonb) from pg_trigger t join pg_class c on c.oid = t.tgrelid
      join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and not t.tgisinternal and t.tgname = any (w.triggers)) as triggers,
    -- informational: anything else already using the weekly names (not created by files 1 and 2, e.g. an add-on file)
    (select coalesce(jsonb_agg(distinct x.name), '[]'::jsonb) from (
        select c.relname::text as name from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and c.relname like 'weekly\\_%%'
        union all
        select p.proname::text from pg_proc p join pg_namespace n on n.oid = p.pronamespace
          where n.nspname = 'public' and (p.proname like 'weekly\\_%%' or p.proname like 'hs\\_weekly\\_%%' or p.proname like '\\_wk\\_%%')) x
      where not (x.name = any (w.relations || w.functions))) as other_weekly_names
  from want w
), pre as (
  select
    -- the admin check every queue function calls: public._hs_is_admin(), no arguments, returns text
    (select jsonb_build_object('exists', count(*) = 1, 'returns', max(pg_get_function_result(p.oid)), 'security_definer', bool_or(p.prosecdef))
       from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public' and p.proname = '_hs_is_admin' and p.pronargs = 0) as admin_helper,
    -- what that helper reads: the dashboard admin list (a COUNT only) and auth.jwt()
    (select case when to_regclass('public.dashboard_admins') is null then null else (xpath('/row/n/text()', query_to_xml('select count(*) as n from public.dashboard_admins', false, true, '')))[1]::text::integer end) as admin_list_rows,
    (to_regprocedure('auth.jwt()') is not null) as auth_jwt_exists,
    -- the topic catalog and the key the queue's foreign keys point at: unique or primary key on exactly (stream, topic)
    (to_regclass('public.alert_topic_catalog') is not null) as catalog_exists,
    (select count(*) from information_schema.columns where table_schema = 'public' and table_name = 'alert_topic_catalog'
       and ((column_name = 'stream' and data_type = 'text') or (column_name = 'topic' and data_type = 'text'))) = 2 as catalog_columns_ok,
    (select exists (select 1 from pg_constraint c where c.conrelid = to_regclass('public.alert_topic_catalog') and c.contype in ('p', 'u')
       and (select array_agg(a.attname::text order by a.attname::text) from unnest(c.conkey) k join pg_attribute a on a.attrelid = c.conrelid and a.attnum = k) = array['stream', 'topic'])) as catalog_key_ok,
    (select case when to_regclass('public.alert_topic_catalog') is null then null else
       (xpath('/row/t/text()', query_to_xml('select coalesce(string_agg(topic, ''|'' order by topic), '''') as t from public.alert_topic_catalog where stream = ''news''', false, true, '')))[1]::text end) as news_categories,
    -- the roles the files revoke from and grant to
    (select coalesce(jsonb_agg(r order by r), '[]'::jsonb) from unnest(array['anon', 'authenticated', 'service_role']) r where not exists (select 1 from pg_roles where rolname = r)) as roles_missing,
    -- built-ins the files use
    (to_regprocedure('gen_random_uuid()') is not null and to_regprocedure('sha256(bytea)') is not null) as builtins_ok,
    current_setting('server_version_num')::integer as server_version_num
)
select jsonb_pretty(jsonb_build_object(
  'checked_at', now(),
  'release', 'queue-only: docs/weekly-1-base.sql + docs/weekly-2-topic-queue.sql',
  'prerequisites', jsonb_build_object(
    'admin_helper', p.admin_helper, 'admin_list_rows', p.admin_list_rows, 'auth_jwt_exists', p.auth_jwt_exists,
    'catalog_exists', p.catalog_exists, 'catalog_columns_ok', p.catalog_columns_ok, 'catalog_key_ok', p.catalog_key_ok,
    'news_categories', string_to_array(coalesce(p.news_categories, ''), '|'),
    'categories_missing', (select coalesce(jsonb_agg(c order by c), '[]'::jsonb) from unnest(w.categories) c
                           where not (c = any (string_to_array(coalesce(p.news_categories, ''), '|')))),
    'roles_missing', p.roles_missing, 'builtins_ok', p.builtins_ok, 'server_version_num', p.server_version_num),
  'will_create', jsonb_build_object('relations', cardinality(w.relations), 'functions', cardinality(w.functions), 'types', cardinality(w.types),
                                    'constraints', cardinality(w.constraints), 'triggers', cardinality(w.triggers)),
  'already_exists', jsonb_build_object('relations', f.relations, 'functions', f.functions, 'types', f.types, 'constraints', f.constraints, 'triggers', f.triggers),
  'other_weekly_names', f.other_weekly_names,
  'verdict', case when
      coalesce((p.admin_helper ->> 'exists')::boolean, false) and p.admin_helper ->> 'returns' = 'text' and coalesce(p.admin_list_rows, 0) > 0 and p.auth_jwt_exists
      and p.catalog_exists and p.catalog_columns_ok and p.catalog_key_ok and p.roles_missing = '[]'::jsonb and p.builtins_ok and p.server_version_num >= 130000
      and not exists (select 1 from unnest(w.categories) c where not (c = any (string_to_array(coalesce(p.news_categories, ''), '|'))))
      and f.relations = '[]'::jsonb and f.functions = '[]'::jsonb and f.types = '[]'::jsonb and f.constraints = '[]'::jsonb and f.triggers = '[]'::jsonb
    then 'go' else 'no-go: see prerequisites and already_exists' end)) as preflight
from want w, found f, pre p;
""" % {k: arr(v) for k, v in dict(new, categories=CATEGORIES).items()}


def main():
    if sys.argv[1] == "--snapshot":
        json.dump(snapshot(), open(sys.argv[3], "w"))
        return
    text = build(json.load(open(sys.argv[2])), json.load(open(sys.argv[3])))
    if sys.argv[1] == "--check":
        if not os.path.exists(OUT) or open(OUT, encoding="utf-8").read() != text:
            sys.exit("docs/weekly-preflight-queue-only.sql differs from what files 1 and 2 create; rebuild it")
        print("the preflight lists exactly what files 1 and 2 create")
    else:
        open(OUT, "w", encoding="utf-8").write(text)
        print("wrote", OUT)


if __name__ == "__main__":
    main()
