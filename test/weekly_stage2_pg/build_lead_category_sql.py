"""Generate docs/weekly-2b-lead-category.sql from file 2. Never edit file 2b by hand.

File 2b makes the database hold the founder's 2026-11-13 rule ("every topic MUST belong to one of the existing 13 Local
News categories"), which the page already enforces:
  - a topic is saved only with a category (a new one, and an existing one being edited);
  - a topic in a report (assigned, no decision or included) keeps that report's category: changing it would leave it
    inside a report of another category.
It replaces ONE function of file 2, hs_weekly_lead_save: the original body with two inserted checks and one inserted
assignment, nothing retyped. --check fails if the committed file differs from what this script makes.

    python3 test/weekly_stage2_pg/build_lead_category_sql.py           # write
    python3 test/weekly_stage2_pg/build_lead_category_sql.py --check   # compare
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import build_queue_lock_sql as base  # noqa: E402

DECL_A = "        isnew boolean := p_lead is null; q text[];\n"
DECL_B = "        isnew boolean := p_lead is null; q text[]; was_topic text;\n"
LOAD_A = "    if l.id is null then raise exception 'unknown lead' using errcode = '22023'; end if;\n  end if;\n"
LOAD_B = "    if l.id is null then raise exception 'unknown lead' using errcode = '22023'; end if;\n    was_topic := l.topic;\n  end if;\n"
CHECK_A = "  if l.topic is not null and not exists (select 1 from public.alert_topic_catalog c where c.stream = 'news' and c.topic = l.topic) then\n"
CHECK_B = ("  if l.topic is null then raise exception 'a topic needs its Local News category' using errcode = '22023'; end if;\n"
           "  if not isnew and l.topic is distinct from was_topic and exists (select 1 from public.weekly_lead_assignments(l.id) x\n"
           "       where x.disposition is null or x.disposition = 'included') then\n"
           "    raise exception 'this topic is in a report; defer or drop it there before changing its category' using errcode = '55006';\n"
           "  end if;\n") + CHECK_A
SUBS = [(DECL_A, DECL_B), (LOAD_A, LOAD_B), (CHECK_A, CHECK_B)]

HEAD = """-- Tab 20 · Weekly Report, 2b: EVERY TOPIC HAS ITS LOCAL NEWS CATEGORY. DDL of record. PREPARED, NOT APPLIED TO PRODUCTION.
-- GENERATED by test/weekly_stage2_pg/build_lead_category_sql.py from file 2. Do not edit by hand.
-- Needs: 1 and 2 (2a may come before or after). One transaction; safe to apply twice. Creates no object.
--
-- hs_weekly_lead_save refuses (SQLSTATE 22023) a topic with no category, new or edited, and refuses (55006) changing the
-- category of a topic that is in a report (no decision there yet, or included). The page already enforces both; this
-- makes the database the authority. A topic with no category already on file keeps its title, sources and notes; the
-- next save must name a category.
-- Owner, privileges, SECURITY DEFINER and search_path are unchanged; the grants below restate file 2's.
-- RE-APPLY HAZARD: re-applying file 2 after this file restores the old body. Re-apply this file after it.
"""
GRANTS = """
do $$
begin
  revoke all on function public.hs_weekly_lead_save(uuid,jsonb) from public, anon, authenticated;
  grant execute on function public.hs_weekly_lead_save(uuid,jsonb) to authenticated;
end $$;
"""
OUT = os.path.join(base.DOCS, "weekly-2b-lead-category.sql")


def build():
    t = base.function_text(base.F2, "hs_weekly_lead_save")
    for a, b in SUBS:
        if t.count(a) != 1:
            raise SystemExit("substitution matches %d times: %r" % (t.count(a), a[:80]))
        t = t.replace(a, b)
    return HEAD + "\nbegin;\n\n-- hs_weekly_lead_save, from docs/%s with the inserted lines above\n" % base.F2 + t + GRANTS + "\ncommit;\n"


def main():
    text = build()
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == text
        print("weekly-2b matches its generator" if ok else "weekly-2b differs from its generator")
        return 0 if ok else 1
    open(OUT, "w", encoding="utf-8").write(text)
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
