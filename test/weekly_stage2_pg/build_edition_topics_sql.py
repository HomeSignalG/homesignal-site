HEAD = """-- Tab 20 · Weekly Report, 9: AN EDITION MAY COVER SEVERAL TOPICS, AND A PUBLISHED EDITION IS LOCKED. DDL of record. PREPARED, NOT APPLIED TO PRODUCTION.
-- GENERATED by test/weekly_stage2_pg/build_edition_topics_sql.py from files 2 and 7. Do not edit by hand.
-- Needs: 1 (base: weekly_append_only), 2 (topic queue), 3 (workbench: weekly_scripts), 7 (version link). Independent of 8.
-- Application order: 1 · 2 · 3 · 4 · 5 · 6 · 7 · 8 · 9. One transaction; safe to apply twice.
--
-- COORDINATION: four of the five functions this file replaces belong to the topic-queue release (file 2) and one to
-- file 7. It is proposed to the topic-queue session and is not to be adopted without its agreement.
--
-- What it does, and what it leaves alone:
--   * An edition keeps its first topic (weekly_editions.topic, NOT NULL, unchanged). A person may add further topics it
--     covers: one append-only row each in weekly_edition_topic_events. weekly_edition_topics(edition) is the first topic
--     followed by the added ones in the order they were added. A topic added by mistake only permits; nothing is removed.
--   * Lead assignment accepts a lead whose topic is any covered topic (it refused anything but the first topic).
--   * A research request made from a lead is filed under THE LEAD'S topic (it used the edition's first topic), so the
--     research, findings, library and script approvals stay per topic, exactly as before.
--   * Linking a script version to an edition accepts a version of any covered topic.
--   * A PUBLISHED edition (our video's address recorded) refuses new assignments, research requests, disposition
--     changes, topic additions and version links, exactly as a CLOSED one already did; the screen hiding those actions
--     was the only protection before. Its sequence, approval and content are locked by 8.
--   * Everything else is unchanged: one lead in one live edition, dispositions, the approval gate (a version linked to an
--     edition is gated on that edition's undecided leads, whatever their topics), closing and publication.
"""

FUNC = re.compile(r"^create or replace function public\.(\w+)\(", re.M)


def function_text(fname, name):
    src = open(os.path.join(DOCS, fname), encoding="utf-8").read()
    starts = [m for m in FUNC.finditer(src) if m.group(1) == name]
    if len(starts) != 1:
        raise SystemExit("%s: %d definitions of %s" % (fname, len(starts), name))
    i = starts[0].start()
    m = re.compile(r"^(end )?\$\$;\n", re.M).search(src, i)
    if not m:
        raise SystemExit("%s: no end for %s" % (fname, name))
    return src[i:m.end()]


LENIENT = False   # --docs mode only: a mutated copy may have rewritten the very line a substitution targets


def replaced(fname, name):
    t = function_text(fname, name)
    for a, b in SUBS[(fname, name)]:
        if LENIENT and t.count(a) == 0:
            continue   # keep the mutated body as it is, so the weakening reaches the combined release
        if t.count(a) != 1:
            raise SystemExit("%s.%s: substitution matches %d times: %r" % (fname, name, t.count(a), a[:80]))
        t = t.replace(a, b)
    return t


NEW = """
create table if not exists public.weekly_edition_topic_events (
  id bigserial primary key,
  edition_id uuid not null references public.weekly_editions (id),
  stream text not null default 'news' check (stream = 'news'),
  topic text not null,
  added_by text not null,
  added_at timestamptz not null default now(),
  constraint weekly_edition_topic_events_topic_fk foreign key (stream, topic) references public.alert_topic_catalog (stream, topic),
  constraint weekly_edition_topic_events_once unique (edition_id, topic)
);

-- The topics one edition covers: its first topic, then the added ones in the order they were added.
create or replace function public.weekly_edition_topics(p_edition uuid) returns text[]
language sql stable security definer set search_path = public as $$
  select array[ed.topic] || coalesce((select array_agg(t.topic order by t.id) from public.weekly_edition_topic_events t
                                      where t.edition_id = ed.id and t.topic <> ed.topic), '{}')
  from public.weekly_editions ed where ed.id = p_edition
$$;

-- A person adds a topic an edition covers. Idempotent; refused on a closed edition or an unknown report category.
create or replace function public.hs_weekly_edition_add_topic(p_edition uuid, p_topic text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare e text := public._hs_is_admin(); ed public.weekly_editions; t text := nullif(btrim(coalesce(p_topic, '')), '');
begin
  select * into ed from public.weekly_editions where id = p_edition for update;
  if ed.id is null then raise exception 'unknown edition' using errcode = '22023'; end if;
  if t is null or not exists (select 1 from public.alert_topic_catalog c where c.stream = 'news' and c.topic = t) then
    raise exception 'unknown report category: %', coalesce(t, '(none)') using errcode = '22023';
  end if;
  if t = any (public.weekly_edition_topics(p_edition)) then
    return jsonb_build_object('edition_id', p_edition, 'topics', to_jsonb(public.weekly_edition_topics(p_edition)), 'existing', true);
  end if;
  if ed.closed_at is not null then raise exception 'edition % is closed', ed.edition_key using errcode = '55000'; end if;
  if ed.video_url is not null then raise exception 'edition % is published; its topics are final', ed.edition_key using errcode = '55000'; end if;
  insert into public.weekly_edition_topic_events (edition_id, topic, added_by) values (p_edition, t, e);
  return jsonb_build_object('edition_id', p_edition, 'topics', to_jsonb(public.weekly_edition_topics(p_edition)), 'existing', false);
end $$;

create or replace function public.hs_weekly_edition_topics(p_edition uuid) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare e text := public._hs_is_admin();
begin
  return jsonb_build_object('edition_id', p_edition, 'topics', to_jsonb(public.weekly_edition_topics(p_edition)));
end $$;
"""

GRANTS = """
do $$
declare f text;
begin
  execute 'drop trigger if exists weekly_edition_topic_events_append_only on public.weekly_edition_topic_events';
  execute 'create trigger weekly_edition_topic_events_append_only before update or delete on public.weekly_edition_topic_events for each row execute function public.weekly_append_only()';
  execute 'alter table public.weekly_edition_topic_events enable row level security';
  execute 'revoke all on public.weekly_edition_topic_events from public, anon, authenticated';
  foreach f in array array['weekly_edition_topics(uuid)', 'hs_weekly_edition_add_topic(uuid,text)', 'hs_weekly_edition_topics(uuid)',
    '_wk_lead_assign(uuid,uuid,text)', 'weekly_lead_request_text(uuid,uuid,text)', 'hs_weekly_lead_send_to_research(uuid,uuid,text)',
    'hs_weekly_edition_link_version(uuid,uuid)', 'hs_weekly_lead_disposition(uuid,uuid,text,text)'] loop
    execute format('revoke all on function public.%s from public, anon, authenticated', f);
  end loop;
  foreach f in array array['hs_weekly_edition_add_topic(uuid,text)', 'hs_weekly_edition_topics(uuid)',
    'hs_weekly_lead_send_to_research(uuid,uuid,text)', 'hs_weekly_edition_link_version(uuid,uuid)',
    'hs_weekly_lead_disposition(uuid,uuid,text,text)'] loop
    execute format('grant execute on function public.%s to authenticated', f);
  end loop;
end $$;
"""


def build():
    parts = [HEAD, "\nbegin;\n", NEW]
    for (fname, name) in SUBS:
        parts.append("\n-- %s, from docs/%s with %d substitution(s) (see the generator)\n" % (name, fname, len(SUBS[(fname, name)])))
        parts.append(replaced(fname, name))
    parts += [GRANTS, "\ncommit;\n"]
    return "".join(parts)


def main():
    global DOCS, OUT
    if "--docs" in sys.argv:   # a copy of docs/ (the topic-queue mutation runner): read from it and write file 9 into it
        global LENIENT
        DOCS, LENIENT = sys.argv[sys.argv.index("--docs") + 1], True
        OUT = os.path.join(DOCS, "weekly-9-edition-topics.sql")
    text = build()
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == text
        print("weekly-9 matches its generator" if ok else "weekly-9 differs from its generator")
        return 0 if ok else 1
    open(OUT, "w", encoding="utf-8").write(text)
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
