#!/usr/bin/env python3
"""Generates the A2 apply and rollback SQL for public._hs_subscriber_zip_health_core() FROM the committed SQL of record,
never by retyping (claims rule 7). Prior definition = git commit 77fdd06 (PR #3054), whose body md5 was confirmed equal to
production's live prosrc md5 (3998bbf2cff02ea15f16e0ac80c03935) on 2026-11-19. New definition = docs/subscriber-zip-health.sql.
Usage: build-subscriber-zip-health-revision.py [--check]   (--check exits 1 if the committed outputs differ)."""
import hashlib, re, subprocess, sys
PRIOR_COMMIT = "77fdd06"
PRIOR_LIVE_MD5 = "3998bbf2cff02ea15f16e0ac80c03935"
RX = re.compile(r"(create or replace function public\._hs_subscriber_zip_health_core\(\).*?as \$\$)(.*?)(\$\$;)", re.S)
def md5(s): return hashlib.md5(s.encode()).hexdigest()
def block(text):
    m = RX.search(text); assert m, "core function not found"
    return m.group(1), m.group(2), m.group(3)
prior_text = subprocess.check_output(["git", "show", f"{PRIOR_COMMIT}:docs/subscriber-zip-health.sql"], text=True)
new_text = open("docs/subscriber-zip-health.sql").read()
ph, pb, pt = block(prior_text); nh, nb, nt = block(new_text)
assert md5(pb) == PRIOR_LIVE_MD5, f"prior body md5 {md5(pb)} != production's recorded {PRIOR_LIVE_MD5}"
NEW_MD5 = md5(nb)

def guard(expect, what):
    return f"""do $g$ begin
  if (select md5(prosrc) from pg_proc where oid = 'public._hs_subscriber_zip_health_core()'::regprocedure) <> '{expect}' then
    raise exception '{what}: live body md5 is not {expect}; refusing';
  end if;
end $g$;
"""
def post(expect):
    return f"""do $g$ begin
  if (select md5(prosrc) from pg_proc where oid = 'public._hs_subscriber_zip_health_core()'::regprocedure) <> '{expect}' then
    raise exception 'post-condition failed: body md5 is not {expect}';
  end if;
  if (select proacl::text from pg_proc where oid = 'public._hs_subscriber_zip_health_core()'::regprocedure) is distinct from '{{postgres=X/postgres,service_role=X/postgres}}' then
    raise exception 'post-condition failed: ACL changed';
  end if;
end $g$;
"""
apply_sql = f"""-- CHANGE GROUP A2 — replaces ONE existing function: public._hs_subscriber_zip_health_core().  GENERATED by
-- scripts/build-subscriber-zip-health-revision.py from docs/subscriber-zip-health.sql. NOT APPLIED.
-- Fail-closed: refuses unless the live body is the PR #3054 body (md5 {PRIOR_LIVE_MD5}). create or replace keeps owner,
-- SECURITY DEFINER, search_path and ACL ({{postgres=X, service_role=X}}); the post-condition asserts the ACL is unchanged.
-- Changes: distinct source keys (not rows); N5-recorded-unresolved keys counted apart ('withheld_by_n5_rule'); 'not_in_serving_generation'
-- now means unexplained only. No table, grant or other function is touched. The reader hs_subscriber_zip_health() is unchanged.
-- New body md5 (after apply): {NEW_MD5}
-- (apply as ONE transaction by apply_migration; do not add begin/commit)
{guard(PRIOR_LIVE_MD5, 'A2 precondition')}
{nh}{nb}{nt}
{post(NEW_MD5)}"""
rollback_sql = f"""-- ROLLBACK for change group A2. GENERATED from git commit {PRIOR_COMMIT} (PR #3054), the text production ran. NOT APPLIED.
-- Fail-closed: refuses unless the live body is the A2 body (md5 {NEW_MD5}); restores the prior body (md5 {PRIOR_LIVE_MD5}).
-- Reversible without data loss: the function holds no state. The A1 lifecycle objects (if applied) keep working with either version.
{guard(NEW_MD5, 'A2 rollback precondition')}
{ph}{pb}{pt}
{post(PRIOR_LIVE_MD5)}"""
outs = {"docs/subscriber-zip-health-core-revision.apply.sql": apply_sql, "docs/subscriber-zip-health-core-revision.rollback.sql": rollback_sql}
if "--check" in sys.argv:
    bad = [p for p, t in outs.items() if open(p).read() != t]
    print("outputs equal their generator" if not bad else "STALE: " + ", ".join(bad)); sys.exit(1 if bad else 0)
for p, t in outs.items(): open(p, "w").write(t)
print("prior body md5", PRIOR_LIVE_MD5, "| new body md5", NEW_MD5)
