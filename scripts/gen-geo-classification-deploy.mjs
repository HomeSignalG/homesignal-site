#!/usr/bin/env node
/**
 * Emit the idempotent, fail-closed SQL that reconciles geo.n5_accepted_source FROM the
 * Git-reviewed disposition file. GENERATED, never hand-written — CLAUDE.md rule 7
 * ("never transcribe a list into a migration; generate it from the source of truth").
 *
 * DISPOSITION -> PRODUCTION ELIGIBILITY CONTRACT
 *   PROVEN, RECOVERY                      -> row present, treatment = disposition. PROCESSABLE.
 *   NOAUTH, HIST_UNRECOVERABLE,
 *   IDENT_UNRESOLVED                      -> row present, treatment = disposition.
 *                                            RECORDED-AND-EXCLUDED: carried into n5_frozen but
 *                                            matched by neither association branch
 *                                            (n5_shard.py:540 PROVEN / :543 RECOVERY).
 *   PENDING_REVIEW, BLOCKED_NO_RECORDS    -> NO ROW. Excluded at the INNER JOIN; a
 *                                            governance hold, enforced by absence.
 *   anything else                         -> the generator REFUSES. Unknown fails closed.
 *
 * WHY NOT EVERY DISPOSITION BECOMES A ROW: presence is not eligibility, but absence is the
 * only mechanism that makes a key UNCLASSIFIED rather than merely non-processable, and a
 * hold must be unclassified.
 *
 * projects/pairs are snapshot-derived counts this file does NOT own. Existing rows keep
 * theirs; a genuinely new row gets 0/0, which is honest (the frozen snapshot has no count
 * for a registry it never saw) and is never used as an eligibility signal.
 *
 * Usage: node scripts/gen-geo-classification-deploy.mjs > docs/geo-classification-deploy.sql
 */
import { readFileSync } from 'node:fs';

const CLS = 'docs/geo-registry-classification.json';
const ROW = new Set(['PROVEN', 'RECOVERY', 'NOAUTH', 'HIST_UNRECOVERABLE', 'IDENT_UNRESOLVED']);
const NOROW = new Set(['PENDING_REVIEW', 'BLOCKED_NO_RECORDS']);

const cls = JSON.parse(readFileSync(CLS, 'utf8'));
const entries = Object.entries(cls.registries || {}).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

const want = [], hold = [];
for (const [id, v] of entries) {
  const d = v && v.disposition;
  if (ROW.has(d)) want.push([id, d]);
  else if (NOROW.has(d)) hold.push([id, d]);
  else {
    console.error(`REFUSED: "${id}" has disposition ${JSON.stringify(d)}, which is neither a `
      + `recorded treatment nor a governance hold. Unknown states fail closed — classify it first.`);
    process.exit(1);
  }
}
const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;
const out = [];
out.push('-- GENERATED by scripts/gen-geo-classification-deploy.mjs — DO NOT HAND-EDIT.');
out.push(`-- Source of truth: ${CLS}`);
out.push(`-- ${want.length} recorded treatment(s) -> rows; ${hold.length} governance hold(s) -> NO row.`);
out.push('-- Idempotent (re-running changes nothing), reversible (it only ever converges to the');
out.push('-- file), and fail-closed (an unknown disposition refuses to generate at all).');
out.push('begin;');
out.push('create temp table _want (registry_id text primary key, treatment text not null) on commit drop;');
if (want.length) {
  out.push('insert into _want (registry_id, treatment) values');
  out.push(want.map(([id, d]) => `  (${lit(id)}, ${lit(d)})`).join(',\n') + ';');
}
out.push('');
out.push('-- (1) upsert recorded treatments; keep existing snapshot-derived counts');
out.push(`insert into geo.n5_accepted_source (registry_id, treatment, projects, pairs)
select w.registry_id, w.treatment,
       coalesce(a.projects, 0), coalesce(a.pairs, 0)
  from _want w left join geo.n5_accepted_source a on a.registry_id = w.registry_id
on conflict (registry_id) do update set treatment = excluded.treatment
 where geo.n5_accepted_source.treatment is distinct from excluded.treatment;`);
out.push('');
out.push('-- (2) governance holds must have NO row — absence is what makes them UNCLASSIFIED');
out.push(`delete from geo.n5_accepted_source a
 where a.registry_id in (${hold.length ? hold.map(([id]) => lit(id)).join(', ') : `''`})
   and a.registry_id <> '(null)';`);
out.push('');
out.push("-- (3) the '(null)' sentinel is NOT a registry (geo joins coalesce a NULL registry_id to");
out.push('--     this literal). It is never emitted by the generator and never deleted here.');
out.push('');
out.push('-- (4) FAIL CLOSED: refuse to commit if the table does not now equal the file.');
out.push(`do $$
declare extra int; missing int; wrong int; held int;
begin
  select count(*) into extra from geo.n5_accepted_source a
   where a.registry_id <> '(null)' and not exists (select 1 from _want w where w.registry_id = a.registry_id);
  select count(*) into missing from _want w
   where not exists (select 1 from geo.n5_accepted_source a where a.registry_id = w.registry_id);
  select count(*) into wrong from _want w join geo.n5_accepted_source a using (registry_id)
   where a.treatment <> w.treatment;
  select count(*) into held from geo.n5_accepted_source a
   where a.registry_id in (${hold.length ? hold.map(([id]) => lit(id)).join(', ') : `''`});
  if extra <> 0 or missing <> 0 or wrong <> 0 or held <> 0 then
    raise exception 'classification deploy REFUSED: extra=% missing=% wrong_treatment=% holds_with_rows=%',
      extra, missing, wrong, held;
  end if;
end $$;`);
out.push('commit;');
console.log(out.join('\n'));
