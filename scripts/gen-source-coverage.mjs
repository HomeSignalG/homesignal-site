#!/usr/bin/env node
// Emits supabase/functions/_shared/source-coverage.generated.json: registry_id -> the registry's own declared coverage [{state, county?}] (a statewide dataset has
// state alone). The report engine bundles only its own tree, so the declared geography is derived mechanically from the registry; `--check` fails CI on drift.
// Used for ONE thing: deciding which sources are geographically applicable to a subject, so a known retrieval failure of such a source is disclosed even when the
// source contributed no record. A source with no declared coverage is simply absent (never applicable by this route).
//   node scripts/gen-source-coverage.mjs          write the file
//   node scripts/gen-source-coverage.mjs --check  exit 1 if the file on disk is not what this would write
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = 'supabase/functions/get-address-report/jurisdiction-registry.json';
const OUT = 'supabase/functions/_shared/source-coverage.generated.json';
const CONNECTORS = ['socrata', 'arcgis', 'ckan', 'csv', 'carto', 'opendatasoft', 'county_cases'];
export function build(registry) {
  const out = {};
  for (const conn of CONNECTORS) for (const e of registry[conn] || []) {
    if (!e || typeof e.registry_id !== 'string' || !Array.isArray(e.coverage) || !e.coverage.length) continue;
    const cov = e.coverage.filter((c) => c && typeof c.state === 'string' && /^[A-Z]{2}$/.test(c.state))
      .map((c) => (typeof c.county === 'string' && c.county ? { state: c.state, county: c.county } : { state: c.state }));
    if (cov.length) out[e.registry_id] = cov;
  }
  return { _doc: 'Generated by scripts/gen-source-coverage.mjs from the source registry. Declared geography per source; do not edit.',
    families: Object.fromEntries(Object.entries(out).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) };
}
const text = JSON.stringify(build(JSON.parse(readFileSync(join(root, SRC), 'utf8'))), null, 2) + '\n';
if (process.argv.includes('--check')) {
  let cur = ''; try { cur = readFileSync(join(root, OUT), 'utf8'); } catch {}
  if (cur !== text) { console.error('source-coverage.generated.json is stale: run node scripts/gen-source-coverage.mjs'); process.exit(1); }
  console.log('source-coverage.generated.json is current');
} else { writeFileSync(join(root, OUT), text); console.log('wrote', OUT); }
