#!/usr/bin/env node
// Emits supabase/functions/_shared/capital-program-sources.generated.json: the registry families whose OWN registry text documents that the dataset is a
// transportation DEVELOPMENT or CAPITAL-PROJECT PROGRAM (a STIP / TIP, a capital or improvement program, a work plan, a delivery plan, a multi-year plan,
// a program book). An agency name alone, or a generic word such as "project", is never evidence. The report engine bundles only its own tree, so this is
// derived mechanically from the registry and `--check` fails CI the moment it differs.
//   node scripts/gen-capital-program-sources.mjs          write the file
//   node scripts/gen-capital-program-sources.mjs --check  exit 1 if the file on disk is not what this would write
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = 'supabase/functions/get-address-report/jurisdiction-registry.json';
const PUB = 'supabase/functions/_shared/source-publishers.generated.json';
const OUT = 'supabase/functions/_shared/capital-program-sources.generated.json';
const CONNECTORS = ['socrata', 'arcgis', 'ckan', 'csv', 'carto', 'county_cases'];
export const TRANSPORT_AGENCY_RE = /department of transportation|\bdot\b|highway|transportation (?:authority|commission|agency|cabinet)|turnpike|\bdoth\b/i;
export const PROGRAM_PHRASE_RE = /(statewide )?transportation improvement program|\bstip\b|\bsyip\b|\bitip\b|capital (?:highway |improvement )?(?:program|investment plan)|improvement program|work ?plan|delivery plan|(?:six|ten|five)[- ]year (?:highway )?(?:plan|program)|program book|construction program|capital projects?/i;
const NOT_PROGRAM_RE = /permit|license|inspection|right.of.way|\brow\b/i;
const FIELDS = ['_receipts', 'why_this_layer', 'dataset_title', 'description', 'jurisdiction'];
export function build(registry, publishers) {
  const out = {};
  for (const conn of CONNECTORS) for (const e of registry[conn] || []) {
    if (!e || typeof e.registry_id !== 'string') continue;
    const id = e.registry_id, agency = publishers[id]?.agency ?? e.jurisdiction ?? '';
    if (!TRANSPORT_AGENCY_RE.test(agency) || NOT_PROGRAM_RE.test(id)) continue;
    for (const f of FIELDS) {
      const text = typeof e[f] === 'string' ? e[f] : JSON.stringify(e[f] ?? '');
      const m = PROGRAM_PHRASE_RE.exec(text);
      if (m) { out[id] = { evidence_field: f, evidence_phrase: m[0].toLowerCase() }; break; }
    }
  }
  return { _doc: 'Generated by scripts/gen-capital-program-sources.mjs from the source registry. A family is listed only when its registry text documents a transportation development or capital-project program. Do not edit.',
    families: Object.fromEntries(Object.entries(out).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) };
}
const reg = JSON.parse(readFileSync(join(root, SRC), 'utf8'));
const pubs = JSON.parse(readFileSync(join(root, PUB), 'utf8')).publishers ?? {};
const text = JSON.stringify(build(reg, pubs), null, 2) + '\n';
if (process.argv.includes('--check')) {
  let cur = ''; try { cur = readFileSync(join(root, OUT), 'utf8'); } catch {}
  if (cur !== text) { console.error('capital-program-sources.generated.json is stale: run node scripts/gen-capital-program-sources.mjs'); process.exit(1); }
  console.log('capital-program-sources.generated.json is current'); 
} else { writeFileSync(join(root, OUT), text); const n = Object.keys(JSON.parse(text).families).length; console.log('wrote ' + OUT + ' (' + n + ' families)'); }
