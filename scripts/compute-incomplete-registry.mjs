#!/usr/bin/env node
// compute-incomplete-registry.mjs — THE canonical computation of the live-metric exclusion list.
//
// An entry is INCOMPLETE for the Live-page metric when its records would render degraded:
//
//   incomplete(e) ⇔  NOT hasUseType(e)  OR  NOT hasStatus(e, family)
//
//   hasUseType(e)         ⇔ 'type_map' ∈ e OR 'use_type_const' ∈ e
//       Without either, use_type falls through to keyword guessing for the pin shape
//       (use_type is the CLOSED six-value vocabulary in lib/map.js::TYPE_EXACT).
//   hasStatus(e, family)  ⇔ status_to_bucket carries ≥1 mapped value
//                           OR (family = 'socrata' AND 'status_const' ∈ e)
//       The socrata clause is REQUIRED, not decorative: socrata's status_const IS the bucket,
//       applied directly, and an all-empty status_to_bucket is the shipped idiom there
//       (east-baton-rouge / marin-county / buffalo / prince-georges — see
//       test/status-const-must-be-mapped.test.mjs, which documents the asymmetry). An arcgis
//       status_const is a RAW value resolved through status_to_bucket, so for arcgis a
//       non-empty map is already implied by that suite; no special clause is needed here.
//
// History: this list was hand-maintained in QUEUE.md (10 entries) and restated per query.
// Verified 2026-08-15 before this script shipped: the computed list matched the hand list
// EXACTLY (10/10, both directions) at registry commit 76ef18a. The naive reading of the old
// written definition — status checked only against status_to_bucket values — would have
// wrongly added the four socrata status_const entries above; that near-miss is why the
// criteria live here in code, with the prose in QUEUE.md required to match.
//
// Usage:
//   node scripts/compute-incomplete-registry.mjs          # JSON report (entries + sha256)
//   node scripts/compute-incomplete-registry.mjs --sql    # full-replace transaction for the
//                                                         # deploy-workflow loader step
//
// Consumers: the loader step in .github/workflows/deploy-edge-functions.yml (writes
// public.registry_incomplete_entries), test/registry-incomplete-entries.test.mjs (pins the
// criteria), and any session query via public.v_incomplete_registry_entries.
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

export const REGISTRY_PATH = new URL(
  '../supabase/functions/get-address-report/jurisdiction-registry.json', import.meta.url);

export function hasUseType(e) {
  return 'type_map' in e || 'use_type_const' in e;
}

export function hasStatus(e, family) {
  const stb = e.status_to_bucket;
  const mapped = stb && typeof stb === 'object' &&
    Object.values(stb).some(v => Array.isArray(v) && v.length > 0);
  if (mapped) return true;
  return family === 'socrata' && 'status_const' in e;
}

/** @returns [{registry_id, family, reason}] sorted by registry_id */
export function computeIncomplete(reg) {
  const out = [];
  for (const [family, entries] of Object.entries(reg)) {
    if (!Array.isArray(entries)) continue;            // _readme keys are strings
    for (const e of entries) {
      if (!e || typeof e !== 'object' || !e.registry_id) continue;
      const reasons = [];
      if (!hasUseType(e)) reasons.push('no type_map and no use_type_const (use_type falls through to keyword guessing)');
      if (!hasStatus(e, family)) reasons.push('no status mechanism (empty status_to_bucket and no socrata status_const)');
      if (reasons.length) out.push({ registry_id: e.registry_id, family, reason: reasons.join('; ') });
    }
  }
  return out.sort((a, b) => a.registry_id.localeCompare(b.registry_id));
}

function main() {
  const raw = readFileSync(REGISTRY_PATH);
  const sha = createHash('sha256').update(raw).digest('hex');
  const reg = JSON.parse(raw.toString('utf8'));
  const entries = computeIncomplete(reg);
  const total = Object.values(reg).filter(Array.isArray)
    .reduce((n, a) => n + a.filter(e => e && typeof e === 'object' && e.registry_id).length, 0);

  if (process.argv.includes('--sql')) {
    // Full replace in ONE transaction: the table is never empty mid-read, and a failed load
    // leaves the previous (still-fingerprinted) list in place rather than a partial one.
    const q = s => `'${String(s).replace(/'/g, "''")}'`;
    const values = entries.map(e =>
      `  (${q(e.registry_id)}, ${q(e.reason)}, ${q(sha)})`).join(',\n');
    process.stdout.write([
      '-- generated by scripts/compute-incomplete-registry.mjs — do not hand-edit',
      `-- registry sha256: ${sha}  (${total} entries scanned, ${entries.length} incomplete)`,
      'begin;',
      'delete from public.registry_incomplete_entries;',
      entries.length
        ? `insert into public.registry_incomplete_entries (registry_id, reason, registry_sha256) values\n${values};`
        : '-- registry currently has ZERO incomplete entries; table left empty on purpose.',
      'commit;',
      "select count(*) as loaded, min(registry_sha256) as sha from public.registry_incomplete_entries;",
      '',
    ].join('\n'));
  } else {
    process.stdout.write(JSON.stringify(
      { registry_sha256: sha, entries_scanned: total, incomplete: entries }, null, 2) + '\n');
  }
}

if (import.meta.url === `file://${process.argv[1]}`) main();
