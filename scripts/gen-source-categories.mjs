#!/usr/bin/env node
// Emits supabase/functions/_shared/source-categories.generated.json: registry_id -> the categories the registry DECLARES the source covers (`coverage_categories`).
// Only sources that declare them appear; a source with none is "not established" for category coverage, never assumed (coverage-categories.ts). The vocabulary is closed:
// an unknown word fails the build, so a typo cannot silently drop a source's coverage. `--check` fails CI on drift.
//   node scripts/gen-source-categories.mjs          write the file
//   node scripts/gen-source-categories.mjs --check  exit 1 if the file on disk is not what this would write
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = 'supabase/functions/get-address-report/jurisdiction-registry.json';
const OUT = 'supabase/functions/_shared/source-categories.generated.json';
const CONNECTORS = ['socrata', 'arcgis', 'ckan', 'csv', 'carto', 'opendatasoft', 'county_cases'];
export const VOCABULARY = ['building_permits', 'planning_zoning', 'subdivision_land_division', 'transportation_capital'];
export function build(registry) {
  const out = {};
  for (const conn of CONNECTORS) for (const e of registry[conn] || []) {
    if (!e || typeof e.registry_id !== 'string' || e.coverage_categories === undefined) continue;
    if (!Array.isArray(e.coverage_categories) || !e.coverage_categories.length) throw new Error(e.registry_id + ': coverage_categories must be a non-empty array');
    for (const c of e.coverage_categories) if (!VOCABULARY.includes(c)) throw new Error(e.registry_id + ': unknown coverage category ' + JSON.stringify(c));
    out[e.registry_id] = [...new Set(e.coverage_categories)].sort();
  }
  return { _doc: 'Generated by scripts/gen-source-categories.mjs from the source registry. Declared categories per source; do not edit.',
    families: Object.fromEntries(Object.entries(out).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) };
}
const text = JSON.stringify(build(JSON.parse(readFileSync(join(root, SRC), 'utf8'))), null, 2) + '\n';
if (process.argv.includes('--check')) {
  let cur = ''; try { cur = readFileSync(join(root, OUT), 'utf8'); } catch {}
  if (cur !== text) { console.error('source-categories.generated.json is stale: run node scripts/gen-source-categories.mjs'); process.exit(1); }
  console.log('source-categories.generated.json is current');
} else { writeFileSync(join(root, OUT), text); console.log('wrote', OUT); }
