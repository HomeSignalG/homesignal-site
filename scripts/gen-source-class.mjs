#!/usr/bin/env node
// Emits supabase/functions/_shared/source-class.generated.json: registry_id -> `source_class`, read from jurisdiction-registry.json, which is the SOLE
// authority for whether a source can ever make a report chargeable (founder decision 2026-11-19). Nothing in the report engine, the view or the credit rule
// decides a class from a name, an agency or a feed shape; it asks this file, and this file is only a bundle-able copy of the registry.
//   local_permit_planning     local building-permit, planning or land-use records. The ONLY class that can make a report chargeable.
//   local_transportation      a local road, right-of-way or capital program. Shown, never charged on its own.
//   statewide_transportation  a state DOT / STIP program. Shown, never charged on its own.
//   statewide_land_use        a statewide land-use register (WA SEPA). Shown, never charged on its own.
// FAIL-CLOSED RULES (each fails this script, and so CI):
//   1. every entry carries a valid source_class (an unclassified source is never chargeable, and is not allowed to exist);
//   2. a statewide entry (a coverage item with no county) can only be a statewide_* class;
//   3. a county-scoped entry can only be a local_* class;
//   4. an entry the capital-program list documents as a transportation program (capital-program-sources.generated.json) can never be local_permit_planning.
//      The list is a cross-check in one direction only: a transportation source it does not list may still be classed transportation, but a listed one can
//      never be classed as a permit source.
//   node scripts/gen-source-class.mjs          write the file
//   node scripts/gen-source-class.mjs --check  exit 1 if the file on disk is not what this would write, or a rule above is broken
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = 'supabase/functions/get-address-report/jurisdiction-registry.json';
const CAP = 'supabase/functions/_shared/capital-program-sources.generated.json';
const OUT = 'supabase/functions/_shared/source-class.generated.json';
export const CONNECTORS = ['socrata', 'arcgis', 'ckan', 'csv', 'carto', 'opendatasoft', 'county_cases'];
export const SOURCE_CLASSES = ['local_permit_planning', 'local_transportation', 'statewide_transportation', 'statewide_land_use'];
export function build(registry, capital) {
  const out = {}, problems = [];
  for (const conn of CONNECTORS) for (const e of registry[conn] || []) {
    if (!e || typeof e.registry_id !== 'string') continue;
    const id = e.registry_id, c = e.source_class;
    if (!SOURCE_CLASSES.includes(c)) { problems.push(`${id}: source_class is ${JSON.stringify(c)}; it must be one of ${SOURCE_CLASSES.join(', ')}`); continue; }
    const cov = Array.isArray(e.coverage) ? e.coverage : [];
    const statewide = cov.some((x) => x && !x.county);
    if (statewide && !c.startsWith('statewide_')) problems.push(`${id}: a statewide entry cannot be ${c}`);
    if (!statewide && cov.length && c.startsWith('statewide_')) problems.push(`${id}: a county-scoped entry cannot be ${c}`);
    if (Object.prototype.hasOwnProperty.call(capital, id) && c === 'local_permit_planning') problems.push(`${id}: documented as a transportation program (capital-program-sources) and cannot be local_permit_planning`);
    if (Object.prototype.hasOwnProperty.call(out, id)) problems.push(`${id}: appears twice in the registry`);
    out[id] = c;
  }
  return { problems, file: { _doc: 'Generated by scripts/gen-source-class.mjs from jurisdiction-registry.json (the sole billing-classification authority). Do not edit.',
    families: Object.fromEntries(Object.entries(out).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) } };
}
if (import.meta.url === `file://${process.argv[1]}`) {
  const reg = JSON.parse(readFileSync(join(root, SRC), 'utf8'));
  const cap = JSON.parse(readFileSync(join(root, CAP), 'utf8')).families ?? {};
  const { problems, file } = build(reg, cap);
  if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
  const text = JSON.stringify(file, null, 2) + '\n';
  if (process.argv.includes('--check')) {
    let cur = ''; try { cur = readFileSync(join(root, OUT), 'utf8'); } catch {}
    if (cur !== text) { console.error('source-class.generated.json is stale: run node scripts/gen-source-class.mjs'); process.exit(1); }
    console.log('source-class.generated.json is current (' + Object.keys(file.families).length + ' sources)');
  } else { writeFileSync(join(root, OUT), text); console.log('wrote', OUT); }
}
